import { cp, mkdir, readFile, writeFile, rm, rename } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = process.argv[2];
if (!target || !target.startsWith('/'))
  throw new Error('Sites checkoutの絶対パスを指定してください。');
const manifestPath = resolve(target, '.openai/hosting.json');
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
if (!manifest.project_id)
  throw new Error('登録済みのSites checkoutを指定してください。');
manifest.d1 = 'DB';
await writeFile(
  manifestPath + '.tmp',
  JSON.stringify(manifest, null, 2) + '\n',
);
await rename(manifestPath + '.tmp', manifestPath);
for (const directory of ['app', 'db', 'drizzle']) {
  await cp(resolve(root, 'sites-host', directory), resolve(target, directory), {
    recursive: true,
  });
}
await rm(resolve(target, 'app/page.tsx'), { force: true });
await mkdir(resolve(target, 'lib'), { recursive: true });
await mkdir(resolve(target, 'game/src/game'), { recursive: true });
await mkdir(resolve(target, 'game/src/online'), { recursive: true });
await cp(resolve(root, 'src/sites'), resolve(target, 'game/src/sites'), {
  recursive: true,
});
for (const file of [
  'physics',
  'geometry',
  'gimmicks',
  'machines',
  'types',
  'tracks',
  'advanced-tracks',
]) {
  await cp(
    resolve(root, `src/game/${file}.ts`),
    resolve(target, `game/src/game/${file}.ts`),
  );
}
await cp(
  resolve(root, 'src/online/protocol.ts'),
  resolve(target, 'game/src/online/protocol.ts'),
);
await cp(resolve(root, 'dist'), resolve(target, 'public'), { recursive: true });
await writeFile(
  resolve(target, 'lib/game-html.ts'),
  `// Generated by scripts/prepare-sites.mjs\nexport const gameHtml = ${JSON.stringify(await readFile(resolve(root, 'dist/index.html'), 'utf8'))};\n`,
);
console.log('Sites向けHTML・画像・共通物理・APIを準備しました。');
